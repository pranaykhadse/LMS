/// Country name + ISO 3166-1 alpha-2 code + international dial code, used
/// for the Account Settings phone-number country picker. The flag is
/// derived from the ISO code at construction time (regional-indicator
/// Unicode trick) instead of being hand-typed per entry.
class Country {
  const Country({required this.name, required this.iso2, required this.dialCode});

  final String name;
  final String iso2;
  final String dialCode;

  /// Renders the ISO2 code as a flag emoji, e.g. "US" -> 🇺🇸. Each letter
  /// maps to a Regional Indicator Symbol (U+1F1E6 = 'A', ...).
  String get flag => iso2
      .toUpperCase()
      .runes
      .map((r) => String.fromCharCode(0x1F1E6 + (r - 0x41)))
      .join();

  @override
  String toString() => '$flag $name (+$dialCode)';
}

